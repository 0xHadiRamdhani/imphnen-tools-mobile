List<ToolDefinition> toolsForCategory(String category) {
  if (category == 'all') return toolCatalog;
  return toolCatalog.where((tool) => tool.category == category).toList();
}

List<ToolDefinition> searchTools(String query, {String category = 'all'}) {
  final normalizedQuery = query.trim().toLowerCase();
  return toolsForCategory(category).where((tool) {
    return tool.name.toLowerCase().contains(normalizedQuery) ||
        tool.description.toLowerCase().contains(normalizedQuery);
  }).toList();
}
